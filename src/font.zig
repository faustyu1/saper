pub const first_char = ' ';
pub const last_char = '~';
const glyph_count = last_char - first_char + 1;

/// Each glyph is seven rows of five bits, most significant bit on the left.
const glyphs: [glyph_count][glyph_height]u5 = blk: {
    @setEvalBranchQuota(200_000);
    var table: [glyph_count][glyph_height]u5 = undefined;
    var lines = std.mem.splitScalar(u8, art, '\n');
    for (0..glyph_count) |g| {
        for (0..glyph_height) |row| {
            const line = lines.next() orelse @compileError("font art ended early");
            if (line.len != glyph_width) @compileError("font art row has the wrong width");
            var bits: u5 = 0;
            for (line) |c| {
                bits = (bits << 1) | @as(u5, if (c == '#') 1 else 0);
            }
            table[g][row] = bits;
        }
    }
    if (lines.next() != null) @compileError("font art has extra rows");
    break :blk table;
};

pub fn charWidth(_: u8) i32 {
    return advance;
}

pub fn textWidth(text: []const u8) i32 {
    if (text.len == 0) return 0;
    return @as(i32, @intCast(text.len)) * advance - 1;
}

pub fn drawChar(fb: *gfx.Framebuffer, x: i32, y: i32, ch: u8, color: gfx.Color) void {
    if (ch < first_char or ch > last_char) return;
    const glyph = glyphs[ch - first_char];
    for (glyph, 0..) |bits, row| {
        var col: u5 = 0;
        while (col < glyph_width) : (col += 1) {
            const mask = @as(u5, 1) << @intCast(glyph_width - 1 - col);
            if (bits & mask != 0) {
                fb.set(x + col, y + @as(i32, @intCast(row)), color);
            }
        }
    }
}

pub fn drawText(fb: *gfx.Framebuffer, x: i32, y: i32, text: []const u8, color: gfx.Color) void {
    var pen = x;
    for (text) |ch| {
        drawChar(fb, pen, y, ch, color);
        pen += advance;
    }
}

/// Draws text with the greyed-out engraved look Windows used for disabled items.
pub fn drawTextDisabled(fb: *gfx.Framebuffer, x: i32, y: i32, text: []const u8) void {
    drawText(fb, x + 1, y + 1, text, gfx.rgb(255, 255, 255));
    drawText(fb, x, y, text, gfx.rgb(128, 128, 128));
}
